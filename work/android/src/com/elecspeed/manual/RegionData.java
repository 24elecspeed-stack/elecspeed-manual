    public static String[] gusFor(String province) {
        String[][] src = "경기도".equals(province) ? GYEONGGI : SEOUL;
        String[] out = new String[src.length];
        for (int i = 0; i < src.length; i++) out[i] = src[i][0];
        return out;
    }

    public static String[] dongsFor(String province, String gu) {
        String[][] src = "경기도".equals(province) ? GYEONGGI : SEOUL;
        for (String[] row : src) {
            if (row[0].equals(gu)) {
                String[] out = new String[row.length - 1];
                System.arraycopy(row, 1, out, 0, out.length);
                return out;
            }
        }
        return new String[0];
    }

    public static String[] randomRegion(String province) {
        String[][] src = "경기도".equals(province) ? GYEONGGI : SEOUL;
        Random r = new Random();
        String[] row = src[r.nextInt(src.length)];
        String gu = row[0];
        String dong = row[1 + r.nextInt(row.length - 1)];
        return new String[]{gu, dong};
    }

